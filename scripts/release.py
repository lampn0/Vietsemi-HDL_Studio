"""Publish the built archives as a GitHub release (tag v<version>).

    python scripts/release.py                 # create the release, or add this build's files to it
    python scripts/release.py --dry-run       # show what would be done, change nothing
    python scripts/release.py --draft         # create it as a draft (publish later on GitHub)
    python scripts/release.py --notes-file notes.md

The version is __version__ of src/version.py; the tag is v<version>. Run it after
scripts/build.py on each platform: the first run (e.g. on Windows) checks the repository, creates
and pushes the tag and creates the release with the archives found in dist/; a later run (e.g. on
Linux) finds the release and uploads its own archives to it (replacing files of the same name).

Checks before anything is changed: GitHub CLI (gh) installed and logged in; on branch main; no
uncommitted changes of tracked files; HEAD pushed to origin/main; an existing tag must point at HEAD.
Untracked files are allowed (they are not part of the release).
"""
from __future__ import annotations

import argparse
import glob
import os
import runpy
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, 'dist')
BRANCH = 'main'


def run(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    """Run a command in the repository root and capture its output."""
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=check)


def out(cmd: list[str]) -> str:
    """Standard output of a command that must succeed, stripped."""
    return run(cmd).stdout.strip()


def fail(msg: str) -> None:
    """Stop with an error message."""
    sys.exit(f'release: {msg}')


def version() -> dict:
    """The names of src/version.py (__version__, APP_NAME, ...)."""
    return runpy.run_path(os.path.join(ROOT, 'src', 'version.py'))


def assets(ver: str) -> list[str]:
    """Archives of this version in dist/ and their .sha256 files."""
    files = sorted(glob.glob(os.path.join(DIST, f'HDLStudio-{ver}-*.zip')) +
                   glob.glob(os.path.join(DIST, f'HDLStudio-{ver}-*.tar.gz')))
    return [p for f in files for p in (f, f + '.sha256') if os.path.isfile(p)]


def check_repo() -> str:
    """Check gh, the branch and that HEAD is committed and pushed; return the HEAD commit."""
    if shutil.which('gh') is None:
        fail('GitHub CLI (gh) not found: https://cli.github.com')
    if run(['gh', 'auth', 'status'], check=False).returncode != 0:
        fail('gh is not logged in: run "gh auth login"')
    branch = out(['git', 'rev-parse', '--abbrev-ref', 'HEAD'])
    if branch != BRANCH:
        fail(f'on branch {branch}; releases are made from {BRANCH}')
    if out(['git', 'status', '--porcelain', '--untracked-files=no']):
        fail('uncommitted changes of tracked files; commit them first')
    run(['git', 'fetch', 'origin', BRANCH, '--tags'])
    head = out(['git', 'rev-parse', 'HEAD'])
    if run(['git', 'merge-base', '--is-ancestor', 'HEAD', f'origin/{BRANCH}'], check=False).returncode != 0:
        fail(f'HEAD is not on origin/{BRANCH}: push it first')
    return head


def main() -> int:
    """Parse the options, check, then create the tag / release or upload to it."""
    ap = argparse.ArgumentParser(description='Publish dist/ archives as the GitHub release v<version>.')
    ap.add_argument('--dry-run', action='store_true', help='print the steps, change nothing')
    ap.add_argument('--draft', action='store_true', help='create the release as a draft')
    ap.add_argument('--prerelease', action='store_true', help='mark the release as a pre-release')
    ap.add_argument('--notes-file', help='release notes (Markdown); default: notes generated by GitHub')
    args = ap.parse_args()

    v = version()
    ver = v['__version__']
    tag = f'v{ver}'
    files = assets(ver)
    if not files:
        fail(f'no archive of {ver} in dist/: run scripts/build.py first')
    head = check_repo()

    steps: list[list[str]] = []
    tag_commit = run(['git', 'rev-parse', '-q', '--verify', f'refs/tags/{tag}^{{commit}}'], check=False).stdout.strip()
    if tag_commit and tag_commit != head:
        fail(f'tag {tag} exists at {tag_commit[:10]}, not at HEAD {head[:10]}: bump __version__ in src/version.py')
    if not tag_commit:
        steps.append(['git', 'tag', '-a', tag, '-m', f'{v["APP_NAME"]} {ver}'])
    if not run(['git', 'ls-remote', '--tags', 'origin', f'refs/tags/{tag}']).stdout.strip():
        steps.append(['git', 'push', 'origin', f'refs/tags/{tag}'])

    exists = run(['gh', 'release', 'view', tag], check=False).returncode == 0
    if exists:
        steps.append(['gh', 'release', 'upload', tag, *files, '--clobber'])
    else:
        cmd = ['gh', 'release', 'create', tag, *files, '--verify-tag', '--title', f'{v["APP_NAME"]} {ver}']
        cmd += ['--notes-file', args.notes_file] if args.notes_file else ['--generate-notes']
        cmd += ['--draft'] if args.draft else []
        cmd += ['--prerelease'] if args.prerelease else []
        steps.append(cmd)

    print(f'{"Upload to" if exists else "Create"} release {tag} with:')
    for f in files:
        print('  ', os.path.relpath(f, ROOT))
    for cmd in steps:
        print('>', ' '.join(os.path.relpath(c, ROOT) if os.path.isabs(c) else c for c in cmd))
        if not args.dry_run:
            r = run(cmd, check=False)
            if r.returncode != 0:
                fail(f'{cmd[0]} {cmd[1]} failed:\n{r.stderr.strip()}')
            if r.stdout.strip():
                print(r.stdout.strip())
    if args.dry_run:
        print('(dry run: nothing changed)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
